"""Authoring only: resolve LTA vector paint/cut operations before browser rendering.

Requires fonttools and skia-pathops in the authoring environment, not on the website.
The source shapes and fingerprint remain in data_reference_geometry.js.
"""
import json
from pathlib import Path
import pathops
from fontTools.svgLib.path import parse_path
from fontTools.pens.svgPathPen import SVGPathPen

FILE = Path(__file__).resolve().parents[1] / 'city/singapore/data_reference_geometry.js'
source = FILE.read_text()
start = source.index('const SG_REFERENCE_GEOMETRY = ') + len('const SG_REFERENCE_GEOMETRY = ')
raw = json.JSONDecoder().raw_decode(source[start:])[0]

def shape(item):
    path = pathops.Path()
    parse_path(item['d'], path.getPen())
    if item.get('fill-rule') == 'evenodd':
        path.fillType = pathops.FillType.EVEN_ODD
    return path

resolved = {}
for line, pieces in raw.items():
    ink = pathops.Path()
    for item in pieces:
        for operation in ['fill', 'stroke']:
            colour = item.get(operation, 'none')
            if colour not in ['line', 'var(--map-bg)']:
                continue
            path = shape(item)
            if operation == 'stroke':
                path.stroke(item['stroke-width'], pathops.LineCap.ROUND_CAP,
                            pathops.LineJoin.ROUND_JOIN, 4)
                path.convertConicsToQuads(0.001)
            ink = pathops.op(ink, path, pathops.PathOp.UNION if colour == 'line' else pathops.PathOp.DIFFERENCE)
    assert ink.area > 0, line
    pen = SVGPathPen(None, ntos=lambda v: format(v, '.4f').rstrip('0').rstrip('.') or '0')
    ink.draw(pen)
    resolved[line] = pen.getCommands()

marker = '// Resolved visible ink; generated by scripts/derive-singapore-route-shapes.py.'
source = source.split(marker)[0].rstrip()
FILE.write_text(source + '\n\n' + marker + '\nconst SG_VISIBLE_ROUTE_GEOMETRY = ' +
                json.dumps(resolved, ensure_ascii=False, indent=2) + ';\n')
print('Resolved', len(resolved), 'routes; no browser masks or local white patches required.')
